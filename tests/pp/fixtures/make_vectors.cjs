// Generates synthetic bcrypt test vectors with bcryptjs (the library the app uses). Throwaway password, no real data.
const b = require('bcryptjs'); const fs = require('fs'); const path = require('path');
const pw = 'Correct-Horse-9';
const h = b.hashSync(pw, 10);
const body = h.slice(4);
const h2b = '$2b$' + body, h2a = '$2a$' + body;
fs.writeFileSync(path.join(__dirname, 'bcrypt_vectors.sh'),
  `# synthetic test vectors generated by bcryptjs\nTEST_PW='${pw}'\nH2B='${h2b}'\nH2A='${h2a}'\n`);
console.log(h2b.slice(0, 7), h2a.slice(0, 7), h.length, b.compareSync(pw, h2a), b.compareSync(pw, h2b));
